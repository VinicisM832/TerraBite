(function carregarReceita() {
    const identificador = new URLSearchParams(window.location.search).get("receita") || "bolo-talhos-beterraba";
    const receita = receitas[identificador] || receitas["bolo-talhos-beterraba"];
    const criarLista = function (seletor, itens) {
        const lista = document.querySelector(seletor);
        lista.innerHTML = itens.map(function (item) {
            return `<li>${item}</li>`;
        }).join("");
    };

    try {
        const receitasLidas = JSON.parse(localStorage.getItem("terraBiteReceitasVisitadas")) || [];
        if (!receitasLidas.includes(identificador)) receitasLidas.push(identificador);
        localStorage.setItem("terraBiteReceitasVisitadas", JSON.stringify(receitasLidas));
    } catch (erro) {
        // A leitura continua funcionando mesmo se o navegador bloquear armazenamento.
    }

    document.title = receita.titulo;
    document.getElementById("tituloReceita").textContent = receita.titulo;
    document.getElementById("imagemReceita").src = receita.imagem;
    document.getElementById("imagemReceita").alt = receita.titulo;
    const botaoSalvar = document.getElementById("botaoSalvarReceita");
    botaoSalvar.dataset.salvarId = identificador;
    botaoSalvar.addEventListener("click", function (event) {
        event.preventDefault();
        const salvas = TerraBiteSalvas.ler();
        const indice = salvas.findIndex(function (item) {
            return (typeof item === "string" ? item : item.id) === identificador;
        });
        if (indice >= 0) salvas.splice(indice, 1);
        else salvas.push({ id: identificador, titulo: receita.titulo, imagem: receita.imagem });
        localStorage.setItem("terraBiteReceitasSalvas", JSON.stringify(salvas));
        document.dispatchEvent(new CustomEvent("receitas-salvas-atualizadas"));
    });
    TerraBiteSalvas.configurarBotoes();
    document.getElementById("dificuldadeReceita").textContent = receita.dificuldade;
    document.getElementById("avaliacaoReceita").textContent = receita.avaliacao;
    document.getElementById("tempoReceita").textContent = receita.preparo;
    document.getElementById("tipoReceita").textContent = receita.tipo;
    document.getElementById("reaproveitadasReceita").textContent = receita.reaproveitadas;
    criarLista("#ingredientesReceita", receita.ingredientes);
    document.getElementById("coberturaTitulo").textContent = receita.coberturaTitulo;
    criarLista("#coberturaReceita", receita.cobertura);
    document.getElementById("dicasReceita").innerHTML = receita.dicas.map(function (dica) {
        return `<p>${dica}</p>`;
    }).join("");
    criarLista("#preparoReceita", receita.passos);

    const estrelas = document.getElementById("estrelasReceita");
    const mensagemAvaliacao = document.getElementById("avaliacaoMensagem");
    const chaveAvaliacoes = "terraBiteAvaliacoes_" + identificador;
    const chaveMinhaAvaliacao = "terraBiteMinhaAvaliacao_" + identificador;

    function lerAvaliacoes() {
        try {
            const valores = JSON.parse(localStorage.getItem(chaveAvaliacoes));
            return Array.isArray(valores) ? valores : [];
        } catch (erro) {
            return [];
        }
    }

    function atualizarNota() {
        const avaliacoes = lerAvaliacoes();
        const notaBase = Number.parseFloat(receita.avaliacao) || 0;
        const totalNotas = avaliacoes.length + 1;
        const media = ((notaBase + avaliacoes.reduce((total, nota) => total + nota, 0)) / totalNotas).toFixed(1);
        document.getElementById("avaliacaoReceita").textContent = media + " (" + totalNotas + ")";
    }

    let minhaAvaliacao = 0;
    try {
        minhaAvaliacao = Number(localStorage.getItem(chaveMinhaAvaliacao)) || 0;
    } catch (erro) {
        minhaAvaliacao = 0;
    }

    for (let nota = 1; nota <= 5; nota++) {
        const botao = document.createElement("button");
        botao.type = "button";
        botao.className = "estrela-botao";
        botao.textContent = nota <= minhaAvaliacao ? "★" : "☆";
        botao.setAttribute("aria-label", "Avaliar com " + nota + " estrelas");
        botao.dataset.nota = nota;
        botao.addEventListener("click", function () {
            const novaNota = Number(this.dataset.nota);
            const avaliacoes = lerAvaliacoes();

            if (minhaAvaliacao) {
                const indiceNota = avaliacoes.indexOf(minhaAvaliacao);
                if (indiceNota >= 0) avaliacoes.splice(indiceNota, 1);
            }

            avaliacoes.push(novaNota);
            minhaAvaliacao = novaNota;
            localStorage.setItem(chaveAvaliacoes, JSON.stringify(avaliacoes));
            localStorage.setItem(chaveMinhaAvaliacao, String(novaNota));
            estrelas.querySelectorAll(".estrela-botao").forEach(function (estrela) {
                estrela.textContent = Number(estrela.dataset.nota) <= novaNota ? "★" : "☆";
            });
            mensagemAvaliacao.textContent = "Sua avaliação foi salva.";
            atualizarNota();
        });
        estrelas.appendChild(botao);
    }

    atualizarNota();
})();

(function carregarForum() {
    const identificador = new URLSearchParams(window.location.search).get("receita") || "bolo-talhos-beterraba";
    const comentarioForm = document.getElementById("comentarioForm");
    const comentariosLista = document.getElementById("comentariosLista");
    const forumLogin = document.getElementById("forumLogin");
    const perfilSalvo = lerPerfilDoForum();
    const chaveComentarios = "terraBiteComentarios_" + identificador;
    const chaveUltimoComentarioVisitante = "terraBiteUltimoComentario_" + identificador;
    let indiceComentarioEditando = -1;

    function lerPerfilDoForum() {
        try {
            return JSON.parse(localStorage.getItem("terraBitePerfil"));
        } catch (erro) {
            return null;
        }
    }

    function lerComentarios() {
        try {
            return JSON.parse(localStorage.getItem(chaveComentarios)) || [];
        } catch (erro) {
            return [];
        }
    }

    function desenharComentarios() {
        comentariosLista.innerHTML = "";
        const comentarios = lerComentarios();

        if (comentarios.length === 0) {
            const vazio = document.createElement("p");
            vazio.className = "comentarios-vazios";
            vazio.textContent = "Ainda não há comentários. Seja o primeiro a participar.";
            comentariosLista.appendChild(vazio);
            return;
        }

        comentarios.forEach(function (comentario, indice) {
            const item = document.createElement("article");
            item.className = "comentario";

            const cabecalho = document.createElement("div");
            cabecalho.className = "comentario-cabecalho";

            const autor = document.createElement("strong");
            autor.textContent = comentario.autor;
            cabecalho.appendChild(autor);

            const data = document.createElement("time");
            data.dateTime = comentario.data;
            data.textContent = new Date(comentario.data).toLocaleDateString("pt-BR");
            cabecalho.appendChild(data);

            let ultimoComentarioVisitante = "";
            try {
                ultimoComentarioVisitante = sessionStorage.getItem(chaveUltimoComentarioVisitante) || "";
            } catch (erro) {
                ultimoComentarioVisitante = "";
            }

            const podeEditar = (perfilSalvo && (comentario.autor === perfilSalvo.nome || comentario.autor === perfilSalvo.apelido)) ||
                (comentario.id && comentario.id === ultimoComentarioVisitante);

            if (podeEditar) {
                const editar = document.createElement("button");
                editar.type = "button";
                editar.className = "editar-comentario";
                editar.textContent = "Editar";
                editar.addEventListener("click", function () {
                    indiceComentarioEditando = indice;
                    document.getElementById("comentarioTexto").value = comentario.texto;
                    document.getElementById("comentarioTexto").focus();
                    document.querySelector("#comentarioForm button[type=submit]").textContent = "Salvar comentário";
                });
                cabecalho.appendChild(editar);

                const excluir = document.createElement("button");
                excluir.type = "button";
                excluir.className = "excluir-comentario";
                excluir.textContent = "Excluir";
                excluir.addEventListener("click", async function () {
                    const confirmar = window.confirmarAcaoNaTela || window.confirm;
                    const confirmou = await confirmar("Deseja excluir este comentário?");
                    if (!confirmou) return;

                    const comentariosAtualizados = lerComentarios();
                    comentariosAtualizados.splice(indice, 1);
                    localStorage.setItem(chaveComentarios, JSON.stringify(comentariosAtualizados));
                    if (indiceComentarioEditando === indice) indiceComentarioEditando = -1;
                    document.getElementById("comentarioTexto").value = "";
                    document.querySelector("#comentarioForm button[type=submit]").textContent = "Publicar comentário";
                    desenharComentarios();
                });
                cabecalho.appendChild(excluir);
            }

            const texto = document.createElement("p");
            texto.textContent = comentario.texto;
            item.appendChild(cabecalho);
            item.appendChild(texto);
            comentariosLista.appendChild(item);
        });
    }

    comentarioForm.hidden = false;
    forumLogin.textContent = perfilSalvo
        ? "Você está comentando como " + (perfilSalvo.apelido || perfilSalvo.nome) + "."
        : "Você pode comentar como visitante ou acessar seu perfil para participar da comunidade.";

    desenharComentarios();

    comentarioForm.addEventListener("submit", function (event) {
        event.preventDefault();
        const perfilAtual = lerPerfilDoForum();
        const mensagem = document.getElementById("comentarioMensagem");

        const texto = document.getElementById("comentarioTexto").value.trim();
        if (!texto) return;

        const comentarios = lerComentarios();
        const comentarioAtualizado = {
            id: indiceComentarioEditando >= 0 && comentarios[indiceComentarioEditando].id
                ? comentarios[indiceComentarioEditando].id
                : "comentario-" + Date.now(),
            autor: perfilAtual ? (perfilAtual.apelido || perfilAtual.nome) : "Visitante",
            texto: texto,
            data: new Date().toISOString()
        };

        if (indiceComentarioEditando >= 0) {
            comentarios[indiceComentarioEditando] = comentarioAtualizado;
        } else {
            comentarios.unshift(comentarioAtualizado);
        }

        if (!perfilAtual) {
            try {
                sessionStorage.setItem(chaveUltimoComentarioVisitante, comentarioAtualizado.id);
            } catch (erro) {
                // O comentário continua salvo mesmo sem sessionStorage.
            }
        }

        localStorage.setItem(chaveComentarios, JSON.stringify(comentarios));
        indiceComentarioEditando = -1;
        comentarioForm.reset();
        document.querySelector("#comentarioForm button[type=submit]").textContent = "Publicar comentário";
        mensagem.textContent = "Comentário salvo.";
        desenharComentarios();
    });
})();
